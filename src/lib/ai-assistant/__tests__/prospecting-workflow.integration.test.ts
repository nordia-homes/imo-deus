import { randomUUID } from 'node:crypto';
import { Firestore } from '@google-cloud/firestore';
import { NextRequest } from 'next/server';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ context: null as any, invoke: vi.fn(), queue: vi.fn(), cancel: vi.fn(), plan: vi.fn() }));
vi.mock('@/firebase/admin', () => ({ adminAuth: {} }));
vi.mock('@/lib/firebase-app-hosting', () => ({ requireAgencyUserFromBearerToken: async () => mocks.context }));
vi.mock('@/lib/communications/server', () => ({ CommunicationError: class extends Error { constructor(message: string, public status = 400) { super(message); } }, getConversation: vi.fn(), agencyCollection: (db: Firestore, agency: string, name: string) => db.collection('agencies').doc(agency).collection(name) }));
vi.mock('@/lib/owner-listings/olx-phone-queue', () => ({ upsertProspectingOlxPhoneQueueEntry: mocks.queue, cancelProspectingOlxPhoneQueueEntry: mocks.cancel }));
vi.mock('@/lib/owner-listings/enrichment-queue', () => ({ upsertPubli24ProspectingPhoneQueueEntry: mocks.queue, cancelProspectingPubli24PhoneQueueEntry: mocks.cancel }));
vi.mock('@/lib/owner-listings/olx-agent-connection', () => ({ getAgentOlxConnection: async () => ({ status: 'connected' }) }));
vi.mock('../operations', () => ({ operations: { owner_prospect: { method: 'POST', path: '/api/owner-listings/prospecting' } }, isReadOperation: () => false, invokeOperation: mocks.invoke }));
vi.mock('../workspace', () => ({ getPlan: mocks.plan }));
import { POST } from '@/app/api/owner-listings/prospecting/route';
import { searchProperties } from '../search';
import { selectContext } from '../context-selection';
import { actionSchema, searchSchema } from '../contracts';
import { executeAction } from '../actions';
import { operationResult } from '../operation-result';
import { readPlanOutcomes } from '../plan-outcomes';
import { readResource } from '../access';
import { executeSafePrefix } from '../autonomy';
import { readTimeline } from '../timeline';
import { readOwnerProspects } from '../owner-prospects';

describe.skipIf(!process.env.FIRESTORE_EMULATOR_HOST)('owner search to prospecting on Firestore with simulated phone provider', () => {
  let db: Firestore;
  const agencies: string[] = [], users: string[] = [], listings: string[] = [];
  beforeAll(() => {
    if (!/^(127\.0\.0\.1|localhost):\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '')) throw new Error('Local emulator required');
    db = new Firestore({ projectId: 'demo-imodeus-prospecting-workflow' });
    mocks.invoke.mockImplementation(async (_ctx, input) => {
      const response = await POST(new NextRequest('http://localhost/api/owner-listings/prospecting', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(input.body) }));
      if (!response.ok) throw new Error('Domain handler rejected request');
      return operationResult(input.operation, await response.json());
    });
  });
  afterAll(async () => {
    if (!db) return;
    for (const agency of agencies) await db.recursiveDelete(db.collection('agencies').doc(agency));
    for (const uid of users) await db.collection('users').doc(uid).delete();
    for (const id of listings) await db.collection('ownerListings').doc(id).delete();
    await db.terminate();
  });
  async function fixture() {
    const agencyId = randomUUID(), uid = randomUUID(); agencies.push(agencyId); users.push(uid);
    const ctx = { agencyId, uid, role: 'agent', adminDb: db } as any;
    await db.collection('agencies').doc(agencyId).set({ city: 'Bucuresti', county: 'Bucuresti' });
    await db.collection('users').doc(uid).set({ agencyId, role: 'agent', name: 'Fixture' });
    mocks.context = ctx; mocks.queue.mockClear(); mocks.invoke.mockClear();
    return ctx;
  }
  it('paginates prospect interactions without mixing listings, snapshots or inaccessible events', async () => {
    const ctx = await fixture();
    const agency = db.collection('agencies').doc(ctx.agencyId);
    await agency.collection('ownerListingFavorites').doc('selected').set({ notes: 'Condiții curente', contactOutcome: 'follow_up' });
    for (const id of ['a', 'b', 'c']) await agency.collection('aiOutreachCalls').doc(id).set({ ownerListingId: 'selected', status: 'completed', summary: `Rezultat ${id}`, endedAt: '2026-10-10T07:00:00.000Z' });
    await agency.collection('aiOutreachCalls').doc('other').set({ ownerListingId: 'another', summary: 'Nu aparține prospectului' });
    await agency.collection('tasks').doc('followup').set({ ownerListingId: 'selected', description: 'Revenire', dueDate: '2026-10-24', createdAt: '2026-10-10T08:00:00.000Z', status: 'open' });
    await agency.collection('crmEvents').doc('revoked').set({ actorId: ctx.uid, entities: { listingId: 'selected', conversationId: 'missing' }, capability: 'Private conversation' });
    await agency.collection('crmEvents').doc('visible').set({ actorId: ctx.uid, entities: { listingId: 'selected' }, capability: 'update_prospect' });
    const input = { resource: 'ownerListingFavorites' as const, id: 'selected', limit: 1 };
    const rows: Record<string, any>[] = [];
    let page = await readTimeline(ctx, input), pages = 0;
    expect(page.complete).toBe(false);
    expect(page.currentSnapshot).toMatchObject({ notes: 'Condiții curente', contactOutcome: 'follow_up' });
    expect(page.scope).toMatchObject({ id: 'selected', relatedListingsIncluded: false });
    while (true) {
      rows.push(...page.rows); pages++;
      if (page.complete) break;
      expect(pages).toBeLessThan(10);
      page = await readTimeline(ctx, { ...input, cursor: page.nextCursor! });
    }
    expect(rows.map(row => row.id).sort()).toEqual(['a', 'b', 'c', 'followup', 'visible']);
    expect(rows.find(row => row.id === 'a')).toMatchObject({ source: 'aiOutreachCalls', description: 'Rezultat a', occurredAt: '2026-10-10T07:00:00.000Z' });
    expect(rows.find(row => row.id === 'followup')).toMatchObject({ source: 'tasks', status: 'open', dueDate: '2026-10-24', occurredAt: '2026-10-10T08:00:00.000Z' });
    const other = await fixture();
    await expect(readTimeline(other, input)).rejects.toMatchObject({ status: 404 });
  });
  it('links full Romanian phone variants across pages including inactive prospects without matching names', async () => {
    const ctx = await fixture(), favorites = db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites');
    await favorites.doc('selected').set({ ownerPhone: '0722123456', ownerName: 'Matei Alin' });
    await favorites.doc('a-related').set({ ownerPhone: '+40 722 123 456', isFavoriteActive: false });
    await favorites.doc('z-related').set({ ownerPhone: '0040 722 123 456' });
    for (let i = 0; i < 51; i++) await favorites.doc(`m-${String(i).padStart(2, '0')}`).set({ ownerPhone: '0733123456', ownerName: 'Matei Alin' });
    const first = await readOwnerProspects(ctx, { listingId: 'selected' });
    expect(first.complete).toBe(false); expect(first.nextCursor).toBeTruthy();
    expect(first.rows.map(row => row.id)).toEqual(['a-related']);
    const last = await readOwnerProspects(ctx, { listingId: 'selected', cursor: first.nextCursor! });
    expect(last.complete).toBe(true); expect(last.rows.map(row => row.id)).toEqual(['selected', 'z-related']);
    await favorites.doc('selected').update({ ownerPhone: '0744123456' });
    await expect(readOwnerProspects(ctx, { listingId: 'selected', cursor: first.nextCursor! })).rejects.toThrow('Cursorul');
    await favorites.doc('selected').update({ ownerPhone: '' });
    expect(await readOwnerProspects(ctx, { listingId: 'selected' })).toMatchObject({ rows: [], complete: false, reason: 'missing_valid_phone' });
    await expect(readOwnerProspects(await fixture(), { listingId: 'selected' })).rejects.toMatchObject({ status: 404 });
  });
  it('enriches only agency prospects and preserves ownership and revision checks on takeover', async () => {
    const ctx = await fixture(), id = randomUUID(); listings.push(id);
    const source = db.collection('ownerListings').doc(id);
    await source.set({ publicationStatus: 'ready', isCanonical: true, title: 'Cișmigiu', ownerPhone: '0722123456', ownerName: 'Original', privateField: 'not for assistant' });
    const favorite = db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').doc(id);
    await favorite.set({ isFavoriteActive: true, ownerName: 'Updated', updatedAt: '2026-10-01T07:00:00.000Z', takenByAgentId: 'other' });
    const read = await readResource(ctx, { resource: 'ownerListingFavorites', id, limit: 10 });
    expect(read.rows[0]).toMatchObject({ title: 'Cișmigiu', ownerName: 'Updated', ownerPhone: '0722123456' });
    expect(read.rows[0]).not.toHaveProperty('privateField');
    const action = actionSchema.parse({ kind: 'update_prospect', listingId: id, expectedUpdatedAt: '2026-10-01T07:00:00.000Z', patch: { state: 'taken' } });
    await expect(executeAction(ctx, action, 'other-owner')).rejects.toMatchObject({ status: 403 });
    await favorite.update({ takenByAgentId: null, updatedAt: '2026-10-02T07:00:00.000Z' });
    await expect(executeAction(ctx, action, 'stale')).rejects.toMatchObject({ status: 409 });
    const other = await fixture();
    await expect(readResource(other, { resource: 'ownerListingFavorites', id, limit: 10 })).rejects.toMatchObject({ status: 404 });
    await source.update({ publicationStatus: 'draft' });
    expect((await readResource(ctx, { resource: 'ownerListingFavorites', id, limit: 10 })).rows[0]).not.toHaveProperty('ownerPhone');
  });
  it('saves a requested prospect follow-up with its participant and rejects foreign ownership or mixed links', async () => {
    const ctx = await fixture(), id = randomUUID(); listings.push(id);
    await db.collection('ownerListings').doc(id).set({ title: 'Cișmigiu', ownerName: 'Original', ownerPhone: '0722123456' });
    const favorite = db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').doc(id);
    await favorite.set({ isFavoriteActive: true, ownerName: 'Actual', takenByAgentId: ctx.uid });
    const action = actionSchema.parse({ kind: 'create_task', ownerListingId: id, description: 'Follow-up proprietar', dueDate: '2030-10-27' });
    const executed = await executeSafePrefix(ctx, 'follow-up', [action], 'Programează follow-up peste două săptămâni.');
    expect(executed.actions).toEqual([]); expect(executed.results).toHaveLength(1);
    const tasks = await db.collection('agencies').doc(ctx.agencyId).collection('tasks').get();
    expect(tasks.size).toBe(1);
    expect(tasks.docs[0].data()).toMatchObject({ ownerListingId: id, ownerListingTitle: 'Cișmigiu', participantName: 'Actual', participantPhone: '0722123456', dueDate: '2030-10-27' });
    expect(tasks.docs[0].data()).not.toHaveProperty('startTime');
    expect((await executeSafePrefix(ctx, 'follow-up', [action], 'Programează follow-up.')).results).toEqual(executed.results);
    await expect(executeAction(ctx, { ...action, propertyId: 'unrelated' }, 'mixed')).rejects.toMatchObject({ status: 400 });
    await favorite.update({ takenByAgentId: 'other' });
    await expect(executeAction(ctx, action, 'other')).rejects.toMatchObject({ status: 403 });
    await favorite.update({ takenByAgentId: ctx.uid, isFavoriteActive: false });
    await expect(executeAction(ctx, action, 'inactive')).rejects.toMatchObject({ status: 403 });
    expect((await db.collection('agencies').doc(ctx.agencyId).collection('tasks').get()).size).toBe(1);
  });
  it('saves the call outcome and appends notes exactly once under concurrent replay', async () => {
    const ctx = await fixture(), id = randomUUID();
    const favorite = db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').doc(id);
    await favorite.set({ isFavoriteActive: true, notes: 'Istoric', updatedAt: '2026-10-01T07:00:00.000Z', takenByAgentId: ctx.uid });
    const action = actionSchema.parse({ kind: 'update_prospect', listingId: id, expectedUpdatedAt: '2026-10-01T07:00:00.000Z', patch: { contactOutcome: 'negative', appendNote: 'Refuz la apel.' } });
    const results = await Promise.all([executeAction(ctx, action, 'call'), executeAction(ctx, action, 'call')]);
    expect(results[0]).toEqual(results[1]);
    expect(results[0]).toMatchObject({ contactOutcome: 'negative', appendedNote: 'Refuz la apel.', executionState: 'succeeded' });
    expect((await favorite.get()).data()).toMatchObject({ notes: 'Istoric\nRefuz la apel.', contactOutcome: 'negative', contactOutcomeByAgentId: ctx.uid, takenByAgentId: null });
    await expect(executeAction(ctx, action, 'stale-call')).rejects.toMatchObject({ status: 409 });
    expect((await favorite.get()).data()?.notes).toBe('Istoric\nRefuz la apel.');
  });
  it('preserves selected order, writes through the existing handler once, then verifies current list membership', async () => {
    const ctx = await fixture(), ids = ['a','b','c'].map(suffix => ctx.agencyId + suffix); listings.push(...ids);
    for (const id of ids) await db.collection('ownerListings').doc(id).set({ scopeKey: 'bucuresti-ilfov', publicationStatus: 'ready', isCanonical: true, title: 'Apartament Drumul Taberei', location: 'Drumul Taberei', price: '120000 EUR', roomsValue: 3, propertyType: 'apartment', transactionType: 'sale', source: 'olx', link: `https://www.olx.ro/d/oferta/${id}.html` });
    const search = searchSchema.parse({ scopeKey: 'bucuresti-ilfov', zone: 'Drumul Taberei', rooms: 3, priceMax: 150000, limit: 100 });
    const found = await searchProperties(ctx, search);
    const orderedIds = found.rows.map(row => row.id);
    expect(orderedIds).toEqual(ids);
    const selected = await selectContext(ctx, { selections: [{ source: 'owners', messageId: 'm', search, orderedIds }] }, { source: 'owners', positions: [3, 1] });
    const actions = selected.rows.map(row => actionSchema.parse({ kind: 'existing_operation', operation: 'owner_prospect', params: {}, query: {}, body: { listingId: row.id, action: 'add' } }));
    expect((await db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').get()).empty).toBe(true);
    const results = [];
    for (const [index, action] of actions.entries()) {
      const key = `approved-${index}`;
      results.push({ step: index + 1, result: await executeAction(ctx, action, key) });
      await executeAction(ctx, action, key);
    }
    expect(mocks.invoke).toHaveBeenCalledTimes(2); expect(mocks.queue).toHaveBeenCalledTimes(2);
    mocks.plan.mockResolvedValue({ data: { status: 'completed', actions, results } });
    const outcome = await readPlanOutcomes(ctx, 'plan');
    expect(outcome).toMatchObject({ outcome: { state: 'COMPLETED', confirmed: 2 }, pollAfterMs: null });
    expect(outcome.rows.every(row => 'businessStatus' in row && row.businessStatus === 'added_to_prospecting')).toBe(true);
    expect(JSON.stringify(outcome)).not.toContain('ownerPhone');
    const favorite = db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').doc(ids[2]);
    await favorite.update({ isFavoriteActive: false });
    expect((await readPlanOutcomes(ctx, 'plan')).outcome.state).toBe('BLOCKED');
    await db.collection('users').doc(ctx.uid).update({ agencyId: 'revoked' });
    await expect(readPlanOutcomes(ctx, 'plan')).rejects.toMatchObject({ status: 403 });
    await expect(executeAction(ctx, actions[0], 'revoked-attempt')).rejects.toMatchObject({ status: 403 });
    expect(mocks.invoke).toHaveBeenCalledTimes(2);
  }, 30000);
  it('polls phone state without rerunning the retry handler and fails closed on cross-agency evidence', async () => {
    const ctx = await fixture(), id = randomUUID(); listings.push(id);
    await db.collection('ownerListings').doc(id).set({ source: 'olx', link: `https://www.olx.ro/d/oferta/${id}.html`, title: 'Fixture' });
    const favorite = db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').doc(id);
    await favorite.set({ isFavoriteActive: true });
    const action = actionSchema.parse({ kind: 'existing_operation', operation: 'owner_prospect', params: {}, query: {}, body: { listingId: id, action: 'retry' } });
    const result = await executeAction(ctx, action, 'retry');
    mocks.plan.mockResolvedValue({ data: { status: 'completed', actions: [action], results: [{ step: 1, result }] } });
    expect(await readPlanOutcomes(ctx, 'plan')).toMatchObject({ outcome: { state: 'WAITING_PROVIDER' }, pollAfterMs: 15000 });
    await favorite.update({ phoneExtractionStatus: 'available', ownerPhone: '0722123456' });
    expect(await readPlanOutcomes(ctx, 'plan')).toMatchObject({ outcome: { state: 'COMPLETED' }, pollAfterMs: null });
    expect(mocks.invoke).toHaveBeenCalledTimes(1); expect(mocks.queue).toHaveBeenCalledTimes(1);
    const other = await fixture();
    expect((await readPlanOutcomes(other, 'plan')).rows[0].executionState).toBe('unavailable');
  }, 30000);
  it('does not infer a completed operation or replay it after the handler writes but phone queueing fails', async () => {
    const ctx = await fixture(), id = randomUUID(); listings.push(id);
    await db.collection('ownerListings').doc(id).set({ source: 'olx', title: 'Fixture', link: `https://www.olx.ro/d/oferta/${id}.html` });
    mocks.queue.mockRejectedValueOnce(new Error('simulated provider outage'));
    const action = actionSchema.parse({ kind: 'existing_operation', operation: 'owner_prospect', params: {}, query: {}, body: { listingId: id, action: 'add' } });
    await expect(executeAction(ctx, action, 'uncertain')).rejects.toThrow('rejected');
    expect((await db.collection('agencies').doc(ctx.agencyId).collection('ownerListingFavorites').doc(id).get()).data()?.isFavoriteActive).toBe(true);
    await expect(executeAction(ctx, action, 'uncertain')).rejects.toMatchObject({ status: 409 });
    mocks.plan.mockResolvedValue({ data: { status: 'unknown', actions: [action], results: [], stoppedStep: { step: 1, result: {} } } });
    expect(await readPlanOutcomes(ctx, 'plan')).toMatchObject({ outcome: { state: 'BLOCKED' }, rows: [{ businessStatus: 'unconfirmed_receipt' }] });
    expect(mocks.invoke).toHaveBeenCalledTimes(1);
  }, 30000);
});
